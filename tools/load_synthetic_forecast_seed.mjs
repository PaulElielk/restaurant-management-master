import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import mysql from "../backend/node_modules/mysql2/promise.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const sqlPath = path.join(root, "backend", "sql", "synthetic_forecast_eval_seed.sql");

const highActivityFoods = [1, 2, 3, 4, 10, 11, 13, 16, 17, 24, 30, 37, 38, 42];
const mediumActivityFoods = [5, 6, 7, 8, 12, 15, 18, 20, 21, 25, 26, 29, 31, 36, 39, 40];
const lowActivityFoods = [9, 14, 19, 22, 23, 27, 28, 32, 33, 34, 35, 41];

function formatDateTime(date) {
  const pad = (n) => String(n).padStart(2, "0");
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}T${pad(date.getHours())}:${pad(date.getMinutes())}`;
}

const today = new Date();
today.setHours(12, 0, 0, 0);

const foodPlans = [];
for (const foodId of highActivityFoods) {
  foodPlans.push({ foodId, activeDays: 22 + (foodId % 7), qtyBase: 2 + (foodId % 3) });
}
for (const foodId of mediumActivityFoods) {
  foodPlans.push({ foodId, activeDays: 7 + (foodId % 5), qtyBase: 1 + (foodId % 2) });
}
for (const foodId of lowActivityFoods) {
  foodPlans.push({ foodId, activeDays: 2 + (foodId % 3), qtyBase: 1 });
}

let billId = 50001;
const bills = [];
const details = [];

for (const plan of foodPlans) {
  const spacing = Math.max(1, Math.floor(29 / plan.activeDays));
  const usedDays = new Set();
  for (let i = 0; i < plan.activeDays; i += 1) {
    const dayOffset = Math.min(29, i * spacing + (plan.foodId % Math.max(1, spacing)));
    if (usedDays.has(dayOffset)) continue;
    usedDays.add(dayOffset);

    const when = new Date(today);
    when.setDate(today.getDate() - dayOffset);
    when.setHours(11 + ((plan.foodId + i) % 10), (plan.foodId * 7 + i * 11) % 60, 0, 0);

    const userId = 1001 + ((plan.foodId * 13 + i) % 300);
    const qty = plan.qtyBase + (i % 2);

    bills.push({
      billId,
      userId,
      phone: `0700${String(userId).padStart(4, "0")}`,
      when: formatDateTime(when),
      total: 10000 + qty * 2500,
    });
    details.push({ billId, foodId: plan.foodId, qty });
    billId += 1;
  }
}

const lines = [
  "-- Synthetic demand forecasting evaluation seed dataset",
  "-- Deterministically generated by tools/load_synthetic_forecast_seed.mjs",
  "-- Intended for development forecast evaluation, not production performance claims.",
  "USE db_restaurant_v2;",
  "DELETE FROM billdetails WHERE bill_id BETWEEN 50001 AND 53000;",
  "DELETE FROM billstatus WHERE bill_id BETWEEN 50001 AND 53000;",
  "",
  "INSERT INTO billstatus",
  "  (bill_id, user_id, bill_phone, bill_address, bill_when, bill_method, bill_discount, bill_delivery, bill_total, bill_paid, bill_status)",
  "VALUES",
  bills
    .map(
      (bill) =>
        `  (${bill.billId}, ${bill.userId}, '${bill.phone}', 'Synthetic Forecast Zone', '${bill.when}', 'card', 0, 500, ${bill.total}, 'true', 6)`
    )
    .join(",\n") + ";",
  "",
  "INSERT INTO billdetails (bill_id, food_id, item_qty)",
  "VALUES",
  details.map((detail) => `  (${detail.billId}, ${detail.foodId}, ${detail.qty})`).join(",\n") + ";",
  "",
];

await fs.writeFile(sqlPath, lines.join("\n"), "utf8");

const db = await mysql.createConnection({
  host: "localhost",
  user: "root",
  password: "",
  database: "db_restaurant_v2",
  multipleStatements: true,
});

try {
  await db.query(lines.join("\n"));
  const [rows] = await db.query(`
    SELECT 'forecast_seed_orders' AS metric, COUNT(*) AS value
      FROM billstatus WHERE bill_id BETWEEN 50001 AND 53000
    UNION ALL
    SELECT 'forecast_seed_order_lines', COUNT(*)
      FROM billdetails WHERE bill_id BETWEEN 50001 AND 53000
    UNION ALL
    SELECT 'forecast_seed_distinct_foods', COUNT(DISTINCT food_id)
      FROM billdetails WHERE bill_id BETWEEN 50001 AND 53000
  `);
  console.log(JSON.stringify(rows, null, 2));
  console.log(`Wrote ${sqlPath}`);
} finally {
  await db.end();
}
