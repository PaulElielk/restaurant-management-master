def remove_unused_chatbot_screenshot():
    invalid = FIG_DIR / "figure_5_5_chatbot_interface.png"
    if invalid.exists():
        invalid.unlink()


def main():
    doc = Document(DOCX)
    remove_accidental_front_matter_insertions(doc)
    remove_duplicate_prompt6_sentences(doc)
    replace_list_of_figures(doc)
    insert_chapter_4_figures(doc)
    insert_chapter_5_figures(doc)
    move_api_flow_after_api_table(doc)
    doc.save(DOCX)
    remove_unused_chatbot_screenshot()
    print(f"Updated {DOCX}")


if __name__ == "__main__":
    main()
