def paragraph_text(element) -> str:
    return "".join(t.text or "" for t in element.iter(base.qn("w:t"))).strip()


def clear_and_set(para, text: str):
    para.text = text


def find_paragraph(doc: Document, predicate):
    for para in doc.paragraphs:
        if predicate(para.text.strip()):
            return para
    raise RuntimeError("Required paragraph not found")


def caption_exists(doc: Document, caption: str) -> bool:
    return any(p.text.strip() == caption and p.style.name == "Caption" for p in doc.paragraphs)


def remove_accidental_front_matter_insertions(doc: Document):
    body = doc._body._element
    chapter_1_idx = None
    children = list(body)
    for idx, child in enumerate(children):
        if child.tag.endswith("}p") and paragraph_text(child) == "Chapter 1 - Introduction":
            style = None
            p_style = child.find(base.qn("w:pPr"))
            if p_style is not None:
                style_node = p_style.find(base.qn("w:pStyle"))
                if style_node is not None:
                    style = style_node.get(base.qn("w:val"))
            if style != "Heading1":
                continue
            chapter_1_idx = idx
            break
    if chapter_1_idx is None:
        return
    for child in list(body)[:chapter_1_idx]:
        if child.tag.endswith("}p"):
            text = paragraph_text(child)
            if text.startswith("Figure 4.4 shows the request-response path"):
                body.remove(child)


def remove_duplicate_prompt6_sentences(doc: Document):
    targets = {
        "Figure 5.4 shows the recommendation interface produced after loading the expanded synthetic interaction data into the application database. The displayed recommendation reasons are generated by the implemented recommender rather than manually edited report values.",
        "Figure 5.5 shows the administrator dashboard view after the expanded synthetic forecasting data was loaded into the database. The forecast output is generated by the moving-average velocity endpoint and should be interpreted as development-environment validation, not production restaurant deployment.",
    }
    seen: set[str] = set()
    body = doc._body._element
    for child in list(body):
        if not child.tag.endswith("}p"):
            continue
        text = paragraph_text(child)
        if text in targets:
            if text in seen:
                body.remove(child)
            else:
                seen.add(text)


def move_api_flow_after_api_table(doc: Document):
    body = doc._body._element
    children = list(body)
    intro_text = (
        "Figure 4.4 shows the request-response path used by the frontend, backend routes, controllers, model layer, and database. "
        "This flow is repeated across the menu, ordering, chatbot, recommendation, and administration features."
    )
    caption_text = "Figure 4.4 - Frontend, API, and database interaction flow"

    while True:
        start = end = None
        children = list(body)
        for idx, child in enumerate(children):
            if child.tag.endswith("}p") and paragraph_text(child) == intro_text:
                start = idx
            elif start is not None and child.tag.endswith("}p") and paragraph_text(child) == caption_text:
                end = idx
                break
        if start is None or end is None:
            break
        for child in children[start : end + 1]:
            body.remove(child)

    table_caption_el = None
    for para in doc.paragraphs:
        if para.text.strip() == "Table 4.4 - Main API domains" and para.style.name == "Caption":
            table_caption_el = para._p
            break
    if table_caption_el is None:
        return

    for idx, child in enumerate(children):
        if child is table_caption_el:
            table_caption_idx = idx
            break
    else:
        return

    table_el = None
    for child in children[table_caption_idx + 1 :]:
        if child.tag.endswith("}tbl"):
            table_el = child
            break
        if child.tag.endswith("}p") and paragraph_text(child).startswith("4.12 "):
            break
    if table_el is None:
        return

    anchor = base.add_paragraph_after(doc, table_el, intro_text)
    add_picture_after(doc, anchor, "figure_4_4_frontend_api_database_flow.png", caption_text)


def replace_list_of_figures(doc: Document):
    body = doc._body._element
    children = list(body)
    start = end = None
    for idx, child in enumerate(children):
        if child.tag.endswith("}p"):
            text = paragraph_text(child)
            if text == "List of Figures":
                start = idx
            elif start is not None and text == "List of Tables":
                end = idx
                break
    if start is None or end is None:
        raise RuntimeError("Could not locate List of Figures section")

    for child in children[start + 1 : end]:
        body.remove(child)

    anchor = children[start]
    for item in FIGURE_LIST:
        anchor = base.add_paragraph_after(doc, anchor, item, "List Bullet")


def add_picture_after(doc: Document, anchor, image_name: str, caption: str, width: float = 6.2):
    if caption_exists(doc, caption):
        return anchor
    p = doc.add_paragraph()
    p.alignment = 1
    run = p.add_run()
    run.add_picture(str(FIG_DIR / image_name), width=Inches(width))
    el = base.pop_last_body_element(doc)
    base.add_after(anchor, el)

    cap = doc.add_paragraph(caption, style="Caption")
    cap_el = base.pop_last_body_element(doc)
    base.add_after(el, cap_el)
    return cap_el


def add_intro_after(doc: Document, anchor, text: str):
    return base.add_paragraph_after(doc, anchor, text)


def insert_chapter_4_figures(doc: Document):
    p = find_paragraph(
        doc,
        lambda t: t.startswith("Figure 4.1 - Three-tier system architecture")
        or t.startswith("Figure 4.1 presents the implemented system"),
    )
    clear_and_set(
        p,
        "Figure 4.1 presents the implemented system at a high level, showing how the Vue.js frontend, REST API layer, Express backend, MySQL database, and AI-related modules interact.",
    )
    anchor = add_picture_after(doc, p._p, "figure_4_1_overall_system_architecture.png", "Figure 4.1 - Overall system architecture")

    p = find_paragraph(
        doc,
        lambda t: t.startswith("Figure 4.2 - Entity-relationship overview")
        or t.startswith("Figure 4.2 summarizes the main database entities"),
    )
    clear_and_set(
        p,
        "Figure 4.2 summarizes the main database entities. The diagram distinguishes declared metadata foreign keys from logical relationships enforced by application queries and shared identifier columns.",
    )
    anchor = add_picture_after(doc, p._p, "figure_4_2_database_erd.png", "Figure 4.2 - Database entity relationship diagram")

    if not caption_exists(doc, "Figure 4.4 - Frontend, API, and database interaction flow"):
        p = next(
            para
            for para in doc.paragraphs
            if para.text.strip() == "Table 4.4 - Main API domains" and para.style.name == "Caption"
        )
        anchor = add_intro_after(
            doc,
            p._p,
            "Figure 4.4 shows the request-response path used by the frontend, backend routes, controllers, model layer, and database. This flow is repeated across the menu, ordering, chatbot, recommendation, and administration features.",
        )
        anchor = add_picture_after(doc, anchor, "figure_4_4_frontend_api_database_flow.png", "Figure 4.4 - Frontend, API, and database interaction flow")

    p = find_paragraph(
        doc,
        lambda t: t.startswith("Figure 4.3 - Checkout and order persistence")
        or t.startswith("Figure 4.3 illustrates the customer ordering workflow"),
    )
    clear_and_set(
        p,
        "Figure 4.3 illustrates the customer ordering workflow from menu browsing through cart persistence, checkout, order creation, and administrator order management.",
    )
    anchor = add_picture_after(doc, p._p, "figure_4_3_customer_ordering_workflow.png", "Figure 4.3 - Customer ordering workflow")


def split_inline_figure(para, marker: str):
    text = para.text
    if marker in text:
        clear_and_set(para, text.split(marker, 1)[0].strip())


